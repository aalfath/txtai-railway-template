"""Railway start script for txtai.

- Refuses to start without API_TOKEN, so the API is never public without auth.
- txtai expects TOKEN to be the SHA-256 hash of the bearer token; it is derived here.
- Writes the txtai YAML config (unless CONFIG is set) with the index on the /data volume.
- Starts uvicorn on PORT, dual-stack (IPv4 for the public domain, IPv6 for private networking).
"""
import hashlib
import os
import socket
import sys

token = os.environ.get("API_TOKEN", "")
if len(token) < 16:
    sys.exit("API_TOKEN is missing or shorter than 16 characters. Set it to a long random value.")
os.environ["TOKEN"] = hashlib.sha256(token.encode("utf-8")).hexdigest()

data = os.environ.get("DATA_DIR", "/data")
os.makedirs(os.path.join(data, "hf"), exist_ok=True)

if not os.environ.get("CONFIG"):
    model = os.environ.get("EMBEDDINGS_MODEL") or "sentence-transformers/all-MiniLM-L6-v2"
    llm = os.environ.get("LLM_MODEL", "").strip()
    lines = [
        "# Generated by /railway/start.py. Set CONFIG to a YAML string or file path to replace it.",
        f"path: {data}/index",
        "writable: true",
        "embeddings:",
        f"  path: {model}",
        "  content: true",
        "  graph:",
        "    approximate: false",
        "    minscore: 0.3",
        "mcp: true",
    ]
    if llm:
        lines += [
            "rag:",
            f"  path: {llm}",
            "  system: You answer questions using only the context provided.",
            "  template: |",
            "    Answer the following question using only the context below. If the context does not contain the answer, say so.",
            "    Question: {question}",
            "    Context: {context}",
            "  context: 5",
            "  output: flatten",
        ]
    path = os.path.join(data, "config.yml")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.environ["CONFIG"] = path

port = int(os.environ.get("PORT", "8000"))
print(f"txtai: config {os.environ['CONFIG']}, listening on port {port}", flush=True)

# uvicorn --host :: is IPv6-only (asyncio sets IPV6_V6ONLY), so bind one dual-stack
# socket here and pass it to uvicorn: IPv4 for the public domain, IPv6 for private networking.
sock = socket.socket(socket.AF_INET6, socket.SOCK_STREAM)
sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 0)
sock.bind(("::", port))
sock.set_inheritable(True)
os.execvp("uvicorn", ["uvicorn", "--fd", str(sock.fileno()), "--proxy-headers",
                      "--forwarded-allow-ips", "*", "txtai.api:app"])
